#!/usr/bin/env python3
"""Generate exact USB bridge matches and the app's compatibility list.

Run after editing bridges.json. --check fails if generated files have drifted.
Only plain SAT bridges belong here; vendor commands and NVMe need other implementations.
"""
import argparse
import copy
import json
from pathlib import Path
import plistlib
import re

root = Path(__file__).resolve().parent.parent
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
check = args.parse_args().check
bridges = json.loads((root / 'bridges.json').read_text())['bridges']
seen_ids, seen_keys = set(), set()
for b in bridges:
    assert re.fullmatch('[0-9a-fA-F]{4}', b['vendor']) and re.fullmatch('[0-9a-fA-F]{4}', b['product']), 'Use exact 16-bit USB IDs'
    ids = (int(b['vendor'], 16), int(b['product'], 16))
    assert ids not in seen_ids and b['key'] not in seen_keys, 'Duplicate bridge'
    assert ids[0] != 0 and ids[1] != 0, 'Zero USB ID'
    assert isinstance(b['verified'], bool)
    seen_ids.add(ids)
    seen_keys.add(b['key'])

path = root / 'Driver/Info.plist'
info = plistlib.loads(path.read_bytes())
template = copy.deepcopy(info['IOKitPersonalities']['VIALabsVL715'])
assert template['IOProviderClass'] == 'IOSCSIPeripheralDeviceNub'
assert template['Peripheral Device Type'] == 0
personalities = {}
for b in bridges:
    personality = copy.deepcopy(template)
    personality['IOParentMatch'] = {'IOPropertyMatch': {'idVendor': int(b['vendor'], 16), 'idProduct': int(b['product'], 16)}}
    personalities[b['key']] = personality
info['IOKitPersonalities'] = personalities
plist_output = plistlib.dumps(info, sort_keys=False)

swift = '''// Generated by scripts/generate-bridges.py from bridges.json. Do not edit by hand.
import Foundation

struct BridgeDefinition: Identifiable {
    let name: String
    let vendor: Int
    let product: Int
    let verified: Bool
    var id: String { String(format: "%04x:%04x", vendor, product) }
    var status: String { verified ? "Verified on hardware" : "SAT candidate · untested on macOS" }
}

let bridgeCatalog: [BridgeDefinition] = [
'''
for b in bridges:
    swift += f'    BridgeDefinition(name: {json.dumps(b["name"])}, vendor: 0x{b["vendor"]}, product: 0x{b["product"]}, verified: {str(b["verified"]).lower()}),\n'
swift += ']\n'
outputs = {path: plist_output, root / 'Shared/BridgeCatalog.swift': swift.encode()}
for path, output in outputs.items():
    if check:
        assert path.read_bytes() == output, f'{path.relative_to(root)} is stale; run scripts/generate-bridges.py'
    else:
        path.write_bytes(output)
print(f'{len(bridges)} exact bridge matches {"checked" if check else "generated"}')
